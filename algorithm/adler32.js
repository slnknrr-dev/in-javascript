/* ══════════════════════════════════════════════════════════════════════════
   adler32.js — Adler-32 (RFC 1950 §9)

   Две бегущие суммы по модулю 65521, упакованные в uint32. Считается
   заметно дешевле CRC-32 и заметно хуже ловит ошибки в коротких данных.

     adler32(buf) → uint32

   Не про изображения: это хвост любого zlib-потока — PNG, woff,
   PDF FlateDecode, loose-объекты git.
   ══════════════════════════════════════════════════════════════════════════ */

function adler32(buf) {
  let a = 1, b = 0;
  for (let i = 0; i < buf.length; i++) {
    a = (a + buf[i]) % 65521;
    b = (b + a) % 65521;
  }
  return ((b << 16) | a) >>> 0;
}

export { adler32 };
