/* ══════════════════════════════════════════════════════════════════════════
   minify.js — консервативный минификатор и нормализатор для хеширования

   Одна механика на две задачи:

     minify(src)     → текст без комментариев и лишних пробелов; из него
                       получается артефакт <name>.min.js
     normalize(src)  → ровно тот же текст; его sha256 и есть codeHash файла

   Отсюда главное свойство пайплайна: правка комментария, отступа или
   пустой строки не меняет codeHash, значит не меняет treeHash, значит не
   вызывает пересборку артефактов. Правка кода — вызывает.

   Что делается:
     · комментарии выброшены;
     · пробелы схлопнуты до минимума, нужного, чтобы токены не слиплись;
     · перевод строки между токенами сохранён ровно там, где он был
       в исходнике — одним «\n».

   Чего НЕ делается: переименования идентификаторов, свёртки констант,
   удаления мёртвого кода, переписывания выражений. Для этого нужен разбор
   областей видимости, то есть парсер — он в M1.

   Почему перевод строки сохраняется. От него зависит ASI: `return\nx`
   и `return x` — разные программы. Точно решить, где перевод значим,
   умеет только парсер; сохраняя все переводы как были, мы получаем
   заведомо ту же программу и всё ещё нечувствительный к форматированию
   хеш (отступы, выравнивание и пустые строки схлопываются).
   ══════════════════════════════════════════════════════════════════════════ */

import { tokenize } from './downgrade-tokenize.js';

/* пары символов, которые при склейке дают другой токен */
const MERGES = new Set([
  '++', '--', '+=', '-=', '==', '!=', '<=', '>=', '&&', '||', '??', '=>',
  '**', '<<', '>>', '*=', '/=', '%=', '&=', '|=', '^=', '?.', '..', '...',
  '//', '/*',
]);

const wordish = c => /[A-Za-z0-9_$]/.test(c) || c.charCodeAt(0) > 0x7F;

function needSpace(a, b) {
  const la = a[a.length - 1], fb = b[0];
  if (wordish(la) && wordish(fb)) return true;
  return MERGES.has(la + fb);
}

/* Токены → минимальный текст. */
export function fromTokens(toks) {
  let out = '';
  for (let i = 0; i < toks.length; i++) {
    const t = toks[i];
    if (i > 0) {
      if (t.nl) out += '\n';
      else if (needSpace(out, t.v)) out += ' ';
    }
    out += t.v;
  }
  return out;
}

/* Минифицированный текст. Результат проверяется: повторная токенизация
   обязана дать ту же последовательность значений токенов и те же переводы
   строк. Не сошлось — минификатор соврал, и лучше упасть. */
export function minify(src, { verify = true } = {}) {
  const toks = tokenize(src);
  const out = fromTokens(toks);
  if (verify) {
    const again = tokenize(out);
    if (again.length !== toks.length)
      throw new Error(`minify: было ${toks.length} токенов, стало ${again.length}`);
    for (let i = 0; i < toks.length; i++) {
      if (again[i].v !== toks[i].v)
        throw new Error(`minify: токен ${i} изменился: ${JSON.stringify(toks[i].v)} → ${JSON.stringify(again[i].v)}`);
      if (i > 0 && again[i].nl !== toks[i].nl)
        throw new Error(`minify: токен ${i} (${JSON.stringify(toks[i].v)}) сменил положение относительно перевода строки`);
    }
  }
  return out;
}

/* То же самое под именем, объясняющим вторую роль. */
export const normalize = src => minify(src);
