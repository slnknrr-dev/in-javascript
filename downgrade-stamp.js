/* ══════════════════════════════════════════════════════════════════════════
   stamp.js — шапка артефакта

   Артефакт начинается с комментария, в котором записано дерево, из
   которого он собран: хеш всего дерева и построчно — каждый файл с его
   codeHash. Не «что-то изменилось», а видно что именно.

   Эта же шапка — единственный источник для решения о пересборке: сборщик
   считает treeHash заново и сравнивает с тем, что прочитал из артефакта.
   Отдельного кеша или lock-файла нет: артефакт сам себе манифест.

   В .min-варианте шапка — единственный уцелевший комментарий: она
   приписывается уже после минификации.
   ══════════════════════════════════════════════════════════════════════════ */

import { HASH_FORMAT } from './downgrade-hash.js';

const MARK = 'generated by @slnknrr/downgrade';

/* lowered — что сделало понижение: проходы и runtime (шимы, помощники).
   Выводится из дерева и версии инструмента, в хеш не входит; строка
   нужна читателю — видно, чем артефакт отличается от исходника. */
export function formatStamp({ target, toolVersion, hash, entries, minified = false, lowered = [] }) {
  const w = Math.max(...entries.map(e => e.file.length));
  return [
    '/* ' + MARK + ' ' + toolVersion + ' — target ' + target + (minified ? ' (minified)' : ''),
    '   do not edit: run `npm run emit`',
    '',
    '   tree ' + HASH_FORMAT + ' ' + hash,
    ...entries.map(e => '     ' + e.file.padEnd(w) + '  ' + e.hash),
    ...(lowered.length ? ['', '   lowered: ' + lowered.join(', ')] : []),
    '',
    '   codeHash считается по тексту без комментариев: правка комментария',
    '   не делает артефакт устаревшим. */',
  ].join('\n') + '\n';
}

/* Хеш дерева из уже лежащего на диске артефакта; null, если это не наш
   файл или шапка испорчена. */
export function readStampHash(text) {
  if (!text.startsWith('/* ' + MARK)) return null;
  const end = text.indexOf('*/');
  if (end < 0) return null;
  const m = new RegExp('^\\s*tree\\s+' + HASH_FORMAT + '\\s+([0-9a-f]{64})\\s*$', 'm')
    .exec(text.slice(0, end));
  return m ? m[1] : null;
}

export const isStamped = text => text.startsWith('/* ' + MARK);
