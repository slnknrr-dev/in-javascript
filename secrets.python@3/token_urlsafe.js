export function token_urlsafe(nbytes = 32) {
    const fast =
        nbytes > 4 &&
        nbytes < 257 &&
        (
            (nbytes & (nbytes - 1)) === 0 ||
            nbytes === 96 ||
            nbytes === 192
        );

    const bytes = fillRandomValues(new Uint8Array(nbytes));

    return fast
        ? FAST[nbytes](bytes)
        : encode_long(bytes);
}