/**
 * Generic / slow path.
 *
 * Supports arbitrary byte lengths.
 * Produces unpadded Base64URL.
 */
function encode_long(b) {
    const n = b.length;

    let s = '';
    let i = 0;

    for (; i + 2 < n; i += 3) {
        const a = b[i];
        const c = b[i + 1];
        const d = b[i + 2];

        s += String.fromCharCode(
            B64URL[a >>> 2],
            B64URL[((a & 3) << 4) | (c >>> 4)],
            B64URL[((c & 15) << 2) | (d >>> 6)],
            B64URL[d & 63],
        );
    }

    const r = n - i;

    if (r === 2) {
        const a = b[i];
        const c = b[i + 1];

        s += String.fromCharCode(
            B64URL[a >>> 2],
            B64URL[((a & 3) << 4) | (c >>> 4)],
            B64URL[(c & 15) << 2],
        );
    } else if (r === 1) {
        const a = b[i];

        s += String.fromCharCode(
            B64URL[a >>> 2],
            B64URL[(a & 3) << 4],
        );
    }

    return s;
}


